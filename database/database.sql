-- Vistas de validación no destructivas.
CREATE OR REPLACE VIEW vw_validacion_formularios_estado AS
SELECT
    f.id_formulario,
    f.usuario_id,
    f.sesion_medica_id,
    f.tipo_formulario,
    f.estado,
    COUNT(r.id_respuesta) AS total_respuestas,
    COUNT(DISTINCT r.id_pregunta) AS preguntas_distintas,
    CASE
        WHEN COUNT(r.id_respuesta) = COUNT(DISTINCT r.id_pregunta) THEN 'CORRECTO'
        ELSE 'DUPLICADOS'
    END AS estado_validacion
FROM formularios_estado f
LEFT JOIN respuestas_estado r ON r.id_formulario = f.id_formulario
GROUP BY f.id_formulario;

CREATE OR REPLACE VIEW vw_validacion_retroalimentaciones AS
SELECT
    r.id_retroalimentacion,
    r.sesion_medica_id,
    r.usuario_id,
    r.profesional_id,
    CASE
        WHEN s.id IS NULL THEN 'SESION_INEXISTENTE'
        WHEN s.usuario_id <> r.usuario_id THEN 'PACIENTE_NO_COINCIDE'
        WHEN s.profesional_id <> r.profesional_id THEN 'PROFESIONAL_NO_COINCIDE'
        ELSE 'CORRECTO'
    END AS estado_validacion
FROM retroalimentaciones_sesion r
LEFT JOIN sesiones_medicas s ON s.id = r.sesion_medica_id;


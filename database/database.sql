    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (profesional_id) REFERENCES profesionales(id) ON DELETE RESTRICT ON UPDATE CASCADE

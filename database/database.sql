DO $$
DECLARE
    rec RECORD;
    max_id BIGINT;
BEGIN
    FOR rec IN
        SELECT table_schema, table_name, column_name,
               pg_get_serial_sequence(format('%I.%I', table_schema, table_name), column_name) AS seq_name
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND is_identity = 'YES'
    LOOP
        EXECUTE format('SELECT COALESCE(MAX(%I), 0) FROM %I.%I', rec.column_name, rec.table_schema, rec.table_name)
        INTO max_id;
        IF rec.seq_name IS NOT NULL THEN
            PERFORM setval(rec.seq_name, GREATEST(max_id, 1), max_id > 0);
        END IF;
    END LOOP;
END;

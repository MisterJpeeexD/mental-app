    duracion_minutos INTEGER DEFAULT 45,
    tipo_sesion VARCHAR(20) CHECK (tipo_sesion IN ('online', 'presencial')) DEFAULT 'online',
    estado_sesion VARCHAR(20) CHECK (estado_sesion IN ('programada', 'en_progreso', 'completada', 'cancelada', 'no_asistio')) DEFAULT 'programada',
    url_videollamada VARCHAR(500),
    token_videollamada VARCHAR(500),
    archivo_grabacion VARCHAR(500),

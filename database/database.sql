CREATE OR REPLACE FUNCTION fn_validar_maximo_preguntas_registro()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    total_activas INTEGER;
BEGIN
    IF NEW.tipo_formulario = 'REGISTRO' AND NEW.activa = TRUE THEN
        SELECT COUNT(*) INTO total_activas
        FROM preguntas_estado
        WHERE tipo_formulario = 'REGISTRO'
          AND activa = TRUE
          AND id_pregunta <> COALESCE(NEW.id_pregunta, -1);

        IF total_activas >= 5 THEN
            RAISE EXCEPTION 'No puede haber más de cinco preguntas activas para el formulario de registro';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_maximo_preguntas_registro ON preguntas_estado;
CREATE TRIGGER trg_maximo_preguntas_registro
BEFORE INSERT OR UPDATE OF activa, tipo_formulario ON preguntas_estado
FOR EACH ROW EXECUTE FUNCTION fn_validar_maximo_preguntas_registro();

CREATE OR REPLACE FUNCTION fn_validar_retroalimentacion_sesion()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    sesion_usuario INTEGER;
    sesion_profesional INTEGER;
    formulario_usuario INTEGER;
    formulario_sesion INTEGER;
    formulario_tipo VARCHAR(30);
BEGIN
    SELECT usuario_id, profesional_id
      INTO sesion_usuario, sesion_profesional
      FROM sesiones_medicas
     WHERE id = NEW.sesion_medica_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La sesión médica % no existe', NEW.sesion_medica_id;
    END IF;

    IF NEW.usuario_id <> sesion_usuario THEN
        RAISE EXCEPTION 'El paciente de la retroalimentación no coincide con el paciente de la sesión';
    END IF;

    IF NEW.profesional_id <> sesion_profesional THEN
        RAISE EXCEPTION 'El profesional de la retroalimentación no coincide con el profesional de la sesión';
    END IF;

    IF NEW.id_formulario_estado IS NOT NULL THEN
        SELECT usuario_id, sesion_medica_id, tipo_formulario
          INTO formulario_usuario, formulario_sesion, formulario_tipo
          FROM formularios_estado
         WHERE id_formulario = NEW.id_formulario_estado;

        IF NOT FOUND OR formulario_usuario <> NEW.usuario_id
           OR formulario_sesion <> NEW.sesion_medica_id
           OR formulario_tipo <> 'RETROALIMENTACION_SESION' THEN
            RAISE EXCEPTION 'El formulario de estado no corresponde al paciente y sesión indicados';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;


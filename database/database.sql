-- ============================================================================
-- AbrazaMente / MenteConecta - Esquema PostgreSQL consolidado
-- Migración no destructiva desde MySQL
-- IMPORTANTE: este script NO elimina ni sobrescribe la base MySQL original.
-- Ejecutar sobre una base PostgreSQL vacía creada previamente con codificación UTF-8.
-- ============================================================================

BEGIN;

SET client_encoding = 'UTF8';
SET TIME ZONE 'UTC';
SET search_path TO public;

-- ============================================================================
-- TABLA: ROLES
-- ============================================================================
CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion TEXT,
    permisos_json JSONB,
    estado VARCHAR(20) CHECK (estado IN ('activo', 'inactivo')) DEFAULT 'activo',
    fecha_creacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- TABLA: USUARIOS
-- ============================================================================
CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    run VARCHAR (255) NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE,
    genero VARCHAR(20) CHECK (genero IN ('masculino', 'femenino', 'otro', 'prefiero_no_decir')),
    estado_civil VARCHAR(50),
    ciudad VARCHAR(100),
    telefono VARCHAR(20),
    bio TEXT,
    estado VARCHAR(20) CHECK (estado IN ('activo', 'inactivo', 'suspendido')) DEFAULT 'activo',
    fecha_creacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    fecha_ultimo_login TIMESTAMPTZ
);

-- ============================================================================
-- TABLA: USUARIO_ROLES
-- ============================================================================
CREATE TABLE IF NOT EXISTS usuario_roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    rol_id INTEGER NOT NULL,
    fecha_asignacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_rol UNIQUE (usuario_id, rol_id),
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (rol_id) REFERENCES roles(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- ============================================================================
-- TABLA: DATOS_INICIALES_USUARIO
-- ============================================================================
CREATE TABLE IF NOT EXISTS datos_iniciales_usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE,
    tiene_estres BOOLEAN DEFAULT FALSE,
    tiene_tristeza BOOLEAN DEFAULT FALSE,
    se_siente_desorientado BOOLEAN DEFAULT FALSE,
    trabaja_actualmente BOOLEAN DEFAULT FALSE,
    tiene_red_apoyo BOOLEAN DEFAULT FALSE,
    notas_adicionales TEXT,
    fecha_registro TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- ============================================================================
-- TABLA: ESPECIALIDADES
-- ============================================================================
CREATE TABLE IF NOT EXISTS especialidades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    descripcion TEXT
);

-- ============================================================================
-- TABLA: PROFESIONALES
-- ============================================================================
CREATE TABLE IF NOT EXISTS profesionales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL UNIQUE,
    licencia_profesional VARCHAR(255),
    especialidad_principal_id INTEGER,
    descripcion_profesional TEXT,
    es_voluntario BOOLEAN DEFAULT FALSE,
    tarifa_sesion DECIMAL(10,2),
    biografia_profesional TEXT,
    anos_experiencia INTEGER,
    idiomas VARCHAR(255),
    estado VARCHAR(20) CHECK (estado IN ('activo', 'inactivo', 'suspendido')) DEFAULT 'activo',
    fecha_registro TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (especialidad_principal_id) REFERENCES especialidades(id) ON DELETE SET NULL ON UPDATE CASCADE
);

-- ============================================================================
-- TABLA: DISPONIBILIDAD
-- Descripción: Disponibilidad para usuarios y profesionales
-- ============================================================================
CREATE TABLE IF NOT EXISTS disponibilidad (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER,
    profesional_id INTEGER,
    dia_semana VARCHAR(20) CHECK (dia_semana IN ('lunes', 'martes', 'miercoles', 'jueves', 'viernes', 'sabado', 'domingo')),
    hora_inicio TIME,
    hora_fin TIME,
    es_activa BOOLEAN DEFAULT TRUE,

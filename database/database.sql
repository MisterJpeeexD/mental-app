CREATE TRIGGER trg_validar_retroalimentacion_sesion
BEFORE INSERT OR UPDATE ON retroalimentaciones_sesion
FOR EACH ROW EXECUTE FUNCTION fn_validar_retroalimentacion_sesion();

CREATE OR REPLACE FUNCTION fn_validar_respuesta_estado()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    formulario_tipo VARCHAR(30);
    pregunta_tipo VARCHAR(30);
    pregunta_activa BOOLEAN;
    opcion_activa BOOLEAN;
BEGIN
    SELECT tipo_formulario INTO formulario_tipo
      FROM formularios_estado WHERE id_formulario = NEW.id_formulario;
    SELECT tipo_formulario, activa INTO pregunta_tipo, pregunta_activa
      FROM preguntas_estado WHERE id_pregunta = NEW.id_pregunta;
    SELECT activa INTO opcion_activa
      FROM opciones_estado WHERE id_opcion = NEW.id_opcion;

    IF formulario_tipo IS NULL OR pregunta_tipo IS NULL OR opcion_activa IS NULL THEN
        RAISE EXCEPTION 'Formulario, pregunta u opción inexistente';
    END IF;
    IF formulario_tipo <> pregunta_tipo THEN
        RAISE EXCEPTION 'La pregunta no pertenece al tipo de formulario';
    END IF;
    IF pregunta_activa = FALSE OR opcion_activa = FALSE THEN
        RAISE EXCEPTION 'La pregunta y la opción deben estar activas';
    END IF;
    RETURN NEW;
END;
$$;

